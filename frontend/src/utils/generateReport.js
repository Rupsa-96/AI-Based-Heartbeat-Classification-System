import jsPDF from 'jspdf'
import autoTable from 'jspdf-autotable'

const FEATURE_META = {
  age:      { label: 'Age',                        unit: 'years' },
  sex:      { label: 'Sex',                        unit: '',     map: { 0: 'Female', 1: 'Male' } },
  cp:       { label: 'Chest Pain Type',            unit: '',     map: { 0: 'Typical Angina', 1: 'Atypical Angina', 2: 'Non-Anginal Pain', 3: 'Asymptomatic' } },
  trestbps: { label: 'Resting Blood Pressure',     unit: 'mm Hg' },
  chol:     { label: 'Serum Cholesterol',          unit: 'mg/dl' },
  fbs:      { label: 'Fasting Blood Sugar >120',   unit: '',     map: { 0: 'No (≤120 mg/dl)', 1: 'Yes (>120 mg/dl)' } },
  restecg:  { label: 'Resting ECG Result',         unit: '',     map: { 0: 'Normal', 1: 'ST-T Wave Abnormality', 2: 'Left Ventricular Hypertrophy' } },
  thalach:  { label: 'Max Heart Rate Achieved',    unit: 'bpm' },
  exang:    { label: 'Exercise-Induced Angina',    unit: '',     map: { 0: 'No', 1: 'Yes' } },
  oldpeak:  { label: 'ST Depression (Oldpeak)',    unit: '' },
  slope:    { label: 'ST Segment Slope',           unit: '',     map: { 0: 'Upsloping', 1: 'Flat', 2: 'Downsloping' } },
  ca:       { label: 'Major Vessels (Fluoroscopy)', unit: '' },
  thal:     { label: 'Thalassemia',                unit: '',     map: { 0: 'Normal', 1: 'Fixed Defect', 2: 'Reversible Defect', 3: 'Unknown' } },
}

function fmtFeatureValue(key, val) {
  const meta = FEATURE_META[key]
  if (!meta) return String(val)
  if (meta.map && meta.map[val] !== undefined) return meta.map[val]
  return meta.unit ? `${val} ${meta.unit}` : String(val)
}

function fmtTimestampFull(iso) {
  if (!iso) return new Date().toLocaleString('en-IN', { dateStyle: 'long', timeStyle: 'medium' })
  try {
    return new Date(iso).toLocaleString('en-IN', { dateStyle: 'long', timeStyle: 'medium' })
  } catch {
    return iso
  }
}


const RISK_COLORS = {
  Low:      { fill: [236, 253, 245], text: [6, 95, 70],   accent: [16, 185, 129] },
  Moderate: { fill: [255, 251, 235], text: [120, 53, 15],  accent: [245, 158, 11] },
  High:     { fill: [254, 242, 242], text: [127, 29, 29],  accent: [239, 68, 68] },
}

export function generatePredictionReport({ result, patientData, patientName, recordId, timestamp }) {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' })
  const PW  = doc.internal.pageSize.getWidth()
  const PH  = doc.internal.pageSize.getHeight()
  const ML  = 18
  const MR  = 18
  const CW  = PW - ML - MR
  let   y   = 0

  const risk   = result.risk_level ?? 'Moderate'
  const colors = RISK_COLORS[risk] ?? RISK_COLORS.Moderate
  const pct    = Math.round((result.probability ?? 0) * 100)
  const dt     = fmtTimestampFull(timestamp)

  function setFont(style, size, color = [30, 41, 59]) {
    doc.setFont('helvetica', style)
    doc.setFontSize(size)
    doc.setTextColor(...color)
  }

  function drawHRule(yPos, r = 226, g = 232, b = 240, thickness = 0.3) {
    doc.setDrawColor(r, g, b)
    doc.setLineWidth(thickness)
    doc.line(ML, yPos, PW - MR, yPos)
  }

  function wrapText(text, x, yPos, maxW, lineH) {
    const lines = doc.splitTextToSize(text, maxW)
    doc.text(lines, x, yPos)
    return yPos + lines.length * lineH
  }

  doc.setFillColor(220, 38, 38)
  doc.rect(0, 0, PW, 34, 'F')

  doc.setFillColor(185, 28, 28)
  doc.rect(0, 30, PW, 4, 'F')

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(22)
  doc.setTextColor(255, 255, 255)
  doc.text('\u2665', ML, 20)
  doc.setFontSize(15)
  doc.setTextColor(255, 255, 255)
  doc.text('Heart Disease Risk Prediction Report', ML + 10, 15)

  // Sub-title
  doc.setFontSize(8)
  doc.setTextColor(254, 202, 202)
  doc.text('HeartGuard AI  \u2022  Deep Neural Network Classification  \u2022  Academic Project', ML + 10, 23)

  y = 44

  
  const metaRows   = 1 + (patientName ? 1 : 0) + (recordId ? 1 : 0)
  const metaHeight = 8 + metaRows * 6
  doc.setFillColor(248, 250, 252)
  doc.roundedRect(ML, y, CW, metaHeight, 2, 2, 'F')

  let metaY = y + 5.5

  if (patientName) {
    setFont('normal', 8, [100, 116, 139])
    doc.text('Patient Name:', ML + 4, metaY)
    setFont('bold', 8, [30, 41, 59])
    doc.text(String(patientName), ML + 38, metaY)
    metaY += 6
  }

  setFont('normal', 8, [100, 116, 139])
  doc.text('Report Generated:', ML + 4, metaY)
  setFont('bold', 8, [30, 41, 59])
  doc.text(dt, ML + 38, metaY)
  metaY += 6

  if (recordId) {
    setFont('normal', 8, [100, 116, 139])
    doc.text('History Record #:', ML + 4, metaY)
    setFont('bold', 8, [30, 41, 59])
    doc.text(String(recordId), ML + 38, metaY)
  }

  // Right side label
  setFont('normal', 7, [148, 163, 184])
  doc.text('Generated by HeartGuard AI \u2013 Educational Use Only', PW - MR, y + metaHeight / 2 + 2, { align: 'right' })

  y += metaHeight + 6

  // prediction result card
  setFont('bold', 10, [30, 41, 59])
  doc.text('Prediction Result', ML, y)
  y += 5
  drawHRule(y, 226, 232, 240, 0.4)
  y += 6

  // Coloured result box
  doc.setFillColor(...colors.fill)
  doc.setDrawColor(...colors.accent)
  doc.setLineWidth(0.6)
  doc.roundedRect(ML, y, CW, 28, 3, 3, 'FD')

  // Risk level label (top-right badge)
  const badgeW = 28
  doc.setFillColor(...colors.accent)
  doc.roundedRect(PW - MR - badgeW, y + 4, badgeW, 8, 2, 2, 'F')
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(7.5)
  doc.setTextColor(255, 255, 255)
  doc.text(`${risk.toUpperCase()} RISK`, PW - MR - badgeW / 2, y + 9.2, { align: 'center' })

  // Prediction label
  setFont('normal', 7.5, colors.text)
  doc.text('DNN PREDICTION', ML + 5, y + 8)
  setFont('bold', 11.5, colors.text)
  doc.text(result.prediction ?? '—', ML + 5, y + 15)

  // Probability
  setFont('normal', 7.5, colors.text)
  doc.text('Probability Score:', ML + 5, y + 22)
  setFont('bold', 14, colors.accent)
  doc.text(`${pct}%`, ML + 38, y + 22)

  // Risk scale bar (drawn manually)
  const barX = ML + 70, barY = y + 18, barW = 90, barH = 5
  doc.setFillColor(226, 232, 240)
  doc.roundedRect(barX, barY, barW, barH, 1, 1, 'F')
  const filledW = Math.max(4, (pct / 100) * barW)
  doc.setFillColor(...colors.accent)
  doc.roundedRect(barX, barY, filledW, barH, 1, 1, 'F')
  // Labels
  setFont('normal', 6.5, [148, 163, 184])
  doc.text('0%', barX, barY + barH + 4)
  doc.text('50%', barX + barW / 2 - 3, barY + barH + 4)
  doc.text('100%', barX + barW - 8, barY + barH + 4)

  y += 36

  // risk level legend strip
  const legendItems = [
    { label: 'Low Risk',      range: '0 – 34%',   active: risk === 'Low',      color: [16, 185, 129] },
    { label: 'Moderate Risk', range: '35 – 64%',  active: risk === 'Moderate', color: [245, 158, 11] },
    { label: 'High Risk',     range: '65 – 100%', active: risk === 'High',     color: [239, 68, 68]  },
  ]
  const boxW = CW / 3 - 2
  legendItems.forEach((item, i) => {
    const bx = ML + i * (boxW + 3)
    if (item.active) {
      doc.setFillColor(...item.color.map(c => Math.min(255, c + 190)))
      doc.setDrawColor(...item.color)
      doc.setLineWidth(0.5)
      doc.roundedRect(bx, y, boxW, 11, 2, 2, 'FD')
      setFont('bold', 7.5, item.color)
    } else {
      doc.setFillColor(248, 250, 252)
      doc.setDrawColor(226, 232, 240)
      doc.setLineWidth(0.3)
      doc.roundedRect(bx, y, boxW, 11, 2, 2, 'FD')
      setFont('normal', 7.5, [148, 163, 184])
    }
    doc.text(item.label, bx + boxW / 2, y + 5, { align: 'center' })
    setFont('normal', 6.5, item.active ? item.color : [148, 163, 184])
    doc.text(item.range, bx + boxW / 2, y + 9.5, { align: 'center' })
  })

  y += 18

  // patient clinical parameters table
  setFont('bold', 10, [30, 41, 59])
  doc.text('Patient Clinical Parameters', ML, y)
  y += 5
  drawHRule(y, 226, 232, 240, 0.4)
  y += 4

  const featureKeys = Object.keys(FEATURE_META)
  // Build 2-column table rows: [Feature, Value, Feature, Value]
  const tableRows = []
  for (let i = 0; i < featureKeys.length; i += 2) {
    const k1 = featureKeys[i]
    const k2 = featureKeys[i + 1]
    tableRows.push([
      FEATURE_META[k1].label,
      fmtFeatureValue(k1, patientData[k1]),
      k2 ? FEATURE_META[k2].label : '',
      k2 ? fmtFeatureValue(k2, patientData[k2]) : '',
    ])
  }

  autoTable(doc, {
    startY: y,
    head: [['Parameter', 'Value', 'Parameter', 'Value']],
    body: tableRows,
    margin: { left: ML, right: MR },
    tableWidth: CW,
    styles: {
      fontSize: 8.5,
      cellPadding: { top: 3, bottom: 3, left: 4, right: 4 },
      lineColor: [226, 232, 240],
      lineWidth: 0.2,
      textColor: [30, 41, 59],
    },
    headStyles: {
      fillColor: [30, 41, 59],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 8,
    },
    alternateRowStyles: { fillColor: [248, 250, 252] },
    columnStyles: {
      0: { fontStyle: 'bold', textColor: [71, 85, 105], cellWidth: CW * 0.28 },
      1: { cellWidth: CW * 0.22 },
      2: { fontStyle: 'bold', textColor: [71, 85, 105], cellWidth: CW * 0.28 },
      3: { cellWidth: CW * 0.22 },
    },
  })

  y = doc.lastAutoTable.finalY + 8

  // model info table
  // start a new page if we're getting close to the bottom
  if (y > PH - 80) { doc.addPage(); y = 20 }

  setFont('bold', 10, [30, 41, 59])
  doc.text('Model Information', ML, y)
  y += 5
  drawHRule(y, 226, 232, 240, 0.4)
  y += 4

  autoTable(doc, {
    startY: y,
    body: [
      ['Model Type',    'Deep Neural Network (DNN)'],
      ['Framework',     'TensorFlow / Keras'],
      ['Architecture',  'Input(13) \u2192 Dense(128) + BatchNorm + ReLU + Dropout(30%)'],
      ['',              'Dense(64) + BatchNorm + ReLU + Dropout(30%)'],
      ['',              'Dense(32) + BatchNorm + ReLU + Dropout(20%)'],
      ['',              'Dense(1) + Sigmoid \u2192 Probability [0, 1]'],
      ['Dataset',       'UCI Heart Disease (Cleveland) \u2014 303 samples, 13 features'],
      ['Output',        'Binary Classification: No Disease (0) / Disease (1)'],
      ['Test Accuracy', '~82%  |  ROC-AUC: ~0.91  |  F1-Score: ~0.80'],
      ['Preprocessing', 'StandardScaler (fitted on training data only, applied at inference)'],
    ],
    margin: { left: ML, right: MR },
    tableWidth: CW,
    styles: {
      fontSize: 8,
      cellPadding: { top: 3, bottom: 3, left: 4, right: 4 },
      lineColor: [226, 232, 240],
      lineWidth: 0.2,
      textColor: [30, 41, 59],
      overflow: 'linebreak',
    },
    columnStyles: {
      0: { fontStyle: 'bold', textColor: [71, 85, 105], cellWidth: 38 },
      1: { cellWidth: CW - 38 },
    },
    alternateRowStyles: { fillColor: [248, 250, 252] },
  })

  y = doc.lastAutoTable.finalY + 8

  // disclaimer box
  if (y > PH - 50) { doc.addPage(); y = 20 }

  doc.setFillColor(255, 251, 235)
  doc.setDrawColor(253, 230, 138)
  doc.setLineWidth(0.5)
  doc.roundedRect(ML, y, CW, 26, 3, 3, 'FD')

  setFont('bold', 8.5, [120, 53, 15])
  doc.text('Medical Disclaimer', ML + 4, y + 7)

  const disclaimerText = result.disclaimer ??
    'This prediction is generated by an AI model for educational and research purposes only. ' +
    'It is NOT a medical diagnosis. Please consult a qualified healthcare professional for any medical concerns.'

  setFont('normal', 7.5, [120, 53, 15])
  const disclaimerLines = doc.splitTextToSize(disclaimerText, CW - 8)
  doc.text(disclaimerLines, ML + 4, y + 14)

  y += 30

  // footer on every page
  const totalPages = doc.internal.getNumberOfPages()
  for (let pg = 1; pg <= totalPages; pg++) {
    doc.setPage(pg)
    const footerY = PH - 10

    // Footer rule
    doc.setDrawColor(226, 232, 240)
    doc.setLineWidth(0.3)
    doc.line(ML, footerY - 4, PW - MR, footerY - 4)

    setFont('normal', 7, [148, 163, 184])
    doc.text('HeartGuard AI — Heart Disease Classification Using DNN — Academic Project', ML, footerY)
    doc.text(`Page ${pg} of ${totalPages}`, PW - MR, footerY, { align: 'right' })
  }

  // save the file
  const safeDate = new Date().toISOString().slice(0, 10)
  const riskTag  = risk.toLowerCase()
  const idTag    = recordId ? `_record${recordId}` : ''
  const filename = `heartguard_prediction${idTag}_${riskTag}_${safeDate}.pdf`

  doc.save(filename)
}
