import os
import json
import pickle
import logging
import numpy as np
import tensorflow as tf

logger = logging.getLogger("predictor")

_HERE      = os.path.dirname(os.path.abspath(__file__))

# MODEL_DIR can be overridden via env var so Render Disk or any path works
_MODEL_DIR  = os.environ.get("MODEL_DIR", os.path.join(_HERE, "..", "model"))
MODEL_PATH  = os.path.join(_MODEL_DIR, "heart_disease_model.keras")
SCALER_PATH = os.path.join(_MODEL_DIR, "scaler.pkl")
META_PATH   = os.path.join(_MODEL_DIR, "feature_meta.json")


class HeartDiseasePredictor:

    _instance = None

    def __init__(self):
        self.model        = None
        self.scaler       = None
        self.feature_cols = None
        self.class_counts = None
        self._loaded      = False

    @classmethod
    def get_instance(cls):
        if cls._instance is None:
            cls._instance = cls()
            cls._instance.load()
        return cls._instance

    def load(self):
        if self._loaded:
            return

        if not os.path.exists(MODEL_PATH):
            raise FileNotFoundError(
                f"Trained model not found at {MODEL_PATH}. "
                "Run: python training/train.py"
            )
        logger.info("Loading DNN model from %s", MODEL_PATH)
        self.model = tf.keras.models.load_model(MODEL_PATH)
        logger.info("Model loaded successfully.")

        if not os.path.exists(SCALER_PATH):
            raise FileNotFoundError(
                f"Scaler not found at {SCALER_PATH}. "
                "Run: python training/train.py"
            )
        with open(SCALER_PATH, "rb") as f:
            self.scaler = pickle.load(f)
        logger.info("Scaler loaded.")

        if os.path.exists(META_PATH):
            with open(META_PATH) as f:
                meta = json.load(f)
            self.feature_cols = meta.get("feature_columns", self._default_feature_cols())
            self.class_counts = meta.get("class_counts", {})
        else:
            logger.warning("feature_meta.json not found, using default column order.")
            self.feature_cols = self._default_feature_cols()
            self.class_counts = {}

        self._loaded = True

    @staticmethod
    def _default_feature_cols():
        return [
            "age", "sex", "cp", "trestbps", "chol", "fbs",
            "restecg", "thalach", "exang", "oldpeak", "slope", "ca", "thal"
        ]

    def predict(self, patient_dict: dict) -> dict:
        if not self._loaded:
            self.load()

        try:
            row = [float(patient_dict[col]) for col in self.feature_cols]
        except KeyError as e:
            raise ValueError(f"Missing feature: {e}")

        arr = np.array(row, dtype=np.float32).reshape(1, -1)
        arr_scaled = self.scaler.transform(arr)

        prob = float(self.model.predict(arr_scaled, verbose=0)[0][0])
        prob = round(prob, 4)

        if prob < 0.35:
            risk_level = "Low"
            label      = "Lower likelihood of heart disease"
        elif prob < 0.65:
            risk_level = "Moderate"
            label      = "Moderate likelihood of heart disease"
        else:
            risk_level = "High"
            label      = "Higher likelihood of heart disease"

        return {
            "prediction":  label,
            "probability": prob,
            "risk_level":  risk_level,
            "disclaimer": (
                "This prediction is generated by an AI model for educational "
                "and research purposes only. It is NOT a medical diagnosis. "
                "Please consult a qualified healthcare professional for any "
                "medical concerns."
            ),
        }

    @property
    def is_loaded(self):
        return self._loaded
